"""Export a tree as a Pine Script v6 indicator (signals + active branch).

Each condition becomes a small function. Context-timeframe conditions are
evaluated with ``request.security(..., lookahead = barmerge.lookahead_off)``:
on historical bars a higher-timeframe value then appears on the chart bar where
that higher-timeframe bar closes, which is exactly the Python alignment. On the
live bar the value can still move until the bar is confirmed, so signals are
only marked on confirmed bars.
"""

from __future__ import annotations

from fxgen.conditions.builder import CROSS_WINDOW, RISING_LAG, Condition, calendar_rule_name
from fxgen.errors import TreeError
from fxgen.indicators.base import Feature
from fxgen.indicators.time import CALENDAR_RULES
from fxgen.tree.evaluate import leaf_paths
from fxgen.tree.node import Leaf, Tree, conditions_used, leaves
from fxgen.tree.serialize import to_rules

PINE_TIMEFRAME = {"H1": "60", "H4": "240", "D1": "1D"}


def _ident(text: str) -> str:
    return "".join(ch if ch.isalnum() else "_" for ch in text)


def _function(name: str, body: str) -> list[str]:
    lines = body.split("\n")
    return [f"{name}() =>", *[f"    {line}" for line in lines], ""]


def _condition_body(cond: Condition, feature_fn: str | None) -> str:
    if cond.kind == "above":
        return f"{feature_fn}() > {cond.threshold!r}"
    if cond.kind == "rising":
        return f"_v = {feature_fn}()\n_v > _v[{RISING_LAG}]"
    if cond.kind == "cross_up":
        return f"_v = {feature_fn}()\nnz(ta.barssince(ta.crossover(_v, 0)), 9999) < {CROSS_WINDOW}"
    if cond.kind == "cross_down":
        return f"_v = {feature_fn}()\nnz(ta.barssince(ta.crossunder(_v, 0)), 9999) < {CROSS_WINDOW}"
    rules = {r.name: r for r in CALENDAR_RULES}
    return rules[calendar_rule_name(cond)].pine


def _ternary(tree: Tree, names: dict[str, str], value: dict[int, str], counter: list[int]) -> str:
    if isinstance(tree, Leaf):
        out = value[counter[0]]
        counter[0] += 1
        return out
    t = _ternary(tree.if_true, names, value, counter)
    f = _ternary(tree.if_false, names, value, counter)
    return f"({names[tree.condition]} ? {t} : {f})"


def export_pine(
    tree: Tree,
    conditions: dict[str, Condition],
    features: list[Feature],
    tree_id: str,
    execution_tf: str = "H1",
) -> str:
    """Return the Pine Script v6 source of an indicator reproducing ``tree``."""
    feature_by_name = {f.name: f for f in features}
    used = list(dict.fromkeys(conditions_used(tree)))
    missing = [c for c in used if c not in conditions]
    if missing:
        raise TreeError(f"conditions {missing} are not fitted; cannot export")
    if execution_tf not in PINE_TIMEFRAME:
        raise TreeError(f"unsupported execution timeframe {execution_tf}")

    rules = to_rules(tree, lambda cid: conditions[cid].describe())
    out: list[str] = [
        "//@version=6",
        f'indicator("fxgen tree {tree_id}", overlay = true)',
        "",
        "// Generated by fxgen. Decisions are taken at the close of each bar; the",
        "// backtest fills orders at the open of the next bar.",
        "// Values can differ slightly from the Python backtest when the data feed or",
        "// the daily session boundary differs from the data used for the backtest.",
        "//",
        *[f"// {line}" for line in rules.splitlines()],
        "",
        f'if timeframe.period != "{PINE_TIMEFRAME[execution_tf]}"',
        f'    runtime.error("This tree was built on {execution_tf} bars: switch the chart to {execution_tf}")',
        "",
        'sessionHour = hour(time_close, "UTC")',
        'sessionDay = dayofweek(time_close, "UTC")',
        "",
    ]
    feature_fns: dict[str, str] = {}
    for cid in used:
        cond = conditions[cid]
        if cond.kind == "calendar" or cond.column in feature_fns:
            continue
        feature = feature_by_name.get(cond.feature)
        if feature is None:
            raise TreeError(f"feature {cond.feature} has no Pine definition")
        name = f"f_{_ident(cond.column)}"
        feature_fns[cond.column] = name
        out += [f"// {cond.timeframe} {feature.label}", *_function(name, feature.pine)]

    names: dict[str, str] = {}
    for i, cid in enumerate(used):
        cond = conditions[cid]
        var = f"c{i}"
        names[cid] = var
        body = _condition_body(cond, feature_fns.get(cond.column))
        out.append(f"// {cond.describe()}")
        if cond.kind == "calendar":
            out += [f"bool {var} = {body}", ""]
            continue
        fn = f"{var}_fn"
        out += _function(fn, body)
        if cond.timeframe == execution_tf:
            out += [f"bool {var} = {fn}()", ""]
        else:
            out += [
                f'bool {var} = request.security(syminfo.tickerid, "{PINE_TIMEFRAME[cond.timeframe]}", {fn}(), '
                "lookahead = barmerge.lookahead_off)",
                "",
            ]

    paths = leaf_paths(tree)
    leaf_actions = [leaf.action for _, leaf in leaves(tree)]
    leaf_expr = _ternary(tree, names, {i: str(i) for i in range(len(paths))}, [0])
    action_expr = _ternary(tree, names, {i: str(int(a)) for i, a in enumerate(leaf_actions)}, [0])
    path_list = ", ".join(f'"{p}"' for p in paths)
    action_names = ", ".join(f'"{a.name}"' for a in leaf_actions)
    out += [
        f"int leaf = {leaf_expr}",
        f"int action = {action_expr}",
        f"var array<string> branchPaths = array.from({path_list})",
        f"var array<string> branchActions = array.from({action_names})",
        "",
        "longStart = barstate.isconfirmed and action == 1 and action[1] != 1",
        "shortStart = barstate.isconfirmed and action == -1 and action[1] != -1",
        "",
        "bgcolor(action == 1 ? color.new(color.teal, 88) : action == -1 ? color.new(color.red, 88) : na, title = \"Active signal\")",
        'plotshape(longStart, "Long signal", shape.triangleup, location.belowbar, color.teal, size = size.small)',
        'plotshape(shortStart, "Short signal", shape.triangledown, location.abovebar, color.red, size = size.small)',
        'plot(leaf, "Branch index", display = display.data_window)',
        "",
        "var label branchLabel = na",
        "if barstate.islast",
        "    label.delete(branchLabel)",
        '    branchLabel := label.new(bar_index, high, "Branch " + array.get(branchPaths, leaf) + ": " + '
        "array.get(branchActions, leaf), style = label.style_label_down, color = color.gray, textcolor = color.white)",
        "",
        'alertcondition(longStart, "fxgen long", "fxgen tree: LONG signal at bar close")',
        'alertcondition(shortStart, "fxgen short", "fxgen tree: SHORT signal at bar close")',
    ]
    return "\n".join(out) + "\n"

